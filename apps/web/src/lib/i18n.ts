export const dictionnaires: Record<Langue, Dictionnaire> = { fr, ar };
export const t = (l: Langue) => dictionnaires[l];

/** Libellé localisé d'un objet ayant des champs *_fr / *_ar. */
export function libelle<T extends Record<string, unknown>>(o: T, champ: string, l: Langue): string {
  const v = (l === "ar" ? o[`${champ}_ar`] : undefined) ?? o[`${champ}_fr`] ?? o[champ];
  return String(v ?? "");
}
